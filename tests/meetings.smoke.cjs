const {app,BrowserWindow,screen}=require('electron');
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
app.setPath('userData',fs.mkdtempSync(path.join(app.getPath('temp'),'promax-meetings-')));
app.whenReady().then(async()=>{
  const win=new BrowserWindow({show:false,width:1440,height:1000,webPreferences:{backgroundThrottling:false}});
  await win.loadFile(path.join(__dirname,'..','index.html'));
  const execute=async code=>{const result=await win.webContents.executeJavaScript(`(async()=>{try{return {value:await eval(${JSON.stringify(code)})}}catch(error){return {error:error.stack}}})()`);if(result.error)throw Error(result.error);return result.value;};
  await execute('ProMaxControls.ready');
  assert.equal(await execute("!!window.ProMaxMeetings"),true);
  assert.equal(await execute("!!document.getElementById('export')||!!document.getElementById('import')"),false);
  await execute("ProMaxMeetings.create('Sunday meeting');ProMaxMeetings.addSong();window.testSong=current().id");
  const testSong=await execute('current().id');
  assert.equal(await execute("document.querySelectorAll('.meeting-item').length"),1);
  assert.equal(await execute("document.getElementById('song-library-area').hidden"),true);
  assert.equal(await execute("document.getElementById('meeting-banner').hidden"),false);
  assert.equal(await execute("document.getElementById('meeting-folder-browser').hidden"),true);
  await execute("document.querySelector('.meeting-item-open').click()");
  assert.equal(await execute("document.getElementById('meeting-overview').hidden && !document.getElementById('slides').hidden"),true,'Selecting a song opens its slides');
  await execute(`(async()=>{
    await ProMaxFeatures.importBible(new File([JSON.stringify({name:'Test',verses:[{book:'Matt',chapter:16,verse:26,text:'Test first'},{book:'Matt',chapter:16,verse:27,text:'Test second'}]})],'test.json'));
    ProMaxFeatures.showTab('bible');
    document.getElementById('bible-search').value='Mat 16:26-27';document.getElementById('bible-search').dispatchEvent(new Event('input'));
    document.querySelectorAll('.verse-row input').forEach(c=>{c.checked=true;c.dispatchEvent(new Event('change'))});
    [...document.querySelectorAll('#feature-view button')].find(b=>b.textContent==='Add passage to meeting').click();
  })()`);
  assert.equal(await execute("ProMaxMeetings.folder().items[1].title"),'Matteus 16:26-27');
  await execute("ProMaxMeetings.move(1,-1)");
  assert.equal(await execute("ProMaxMeetings.folder().items[0].type"),'bible');
  await execute("ProMaxMeetings.open(ProMaxMeetings.folder().items[0])");
  assert.equal(await execute("document.querySelectorAll('.prepared-slide').length"),1);
  assert.equal(await execute("state.text"),'','Selecting a passage must not send it live');
  await execute("document.querySelector('.prepared-slide').click()");
  assert.equal(await execute("document.querySelectorAll('#preview .verse-number').length"),2);
  assert.equal(await execute("document.querySelector('.prepared-slide').getAttribute('aria-pressed')"),'true');
  const previousPassage=await execute('state.text');
  await execute("ProMaxMeetings.open(ProMaxMeetings.folder().items[1]);document.querySelector('.slide-edit-button').click();document.getElementById('slide-edit-text').value='Automatically saved words';document.getElementById('slide-edit-text').dispatchEvent(new Event('input'))");
  assert.equal(await execute('state.text'),previousPassage,'Selecting a song preserves the live passage');
  assert.equal(await execute("!document.getElementById('slides').hidden && document.getElementById('meeting-overview').hidden"),true);
  assert.equal(await execute("JSON.parse(localStorage.getItem('promax-library')).songs.find(s=>s.id===selected).slides[0].text"),'Automatically saved words');
  await execute("document.getElementById('slide-edit-cancel').click();document.getElementById('meeting-name').value='Evening meeting';document.getElementById('meeting-name').dispatchEvent(new Event('input'))");
  await win.webContents.reload();
  await new Promise(resolve=>win.webContents.once('did-finish-load',resolve));
  assert.equal(await execute("ProMaxMeetings.folder().name"),'Evening meeting');
  assert.equal(await execute("ProMaxMeetings.folder().items.length"),2);
  assert.equal(await execute("current().slides[0].text"),'Automatically saved words');
  assert.equal(await execute("document.getElementById('meeting-overview').hidden"),true);
  assert.equal(await execute("document.querySelector('.meeting-item.active .meeting-item-open span').textContent"),'Amazing Grace');
  await execute(`(async()=>{
    await ProMaxFeatures.ready;
    await ProMaxFeatures.saveDocument({id:'meeting-test-doc',title:'Meeting slides',slides:['file:///C:/slide-one.png','file:///C:/slide-two.png']});
    ProMaxMeetings.add({type:'document',assetId:'meeting-test-doc',title:'Meeting slides'});
    await ProMaxMeetings.open(ProMaxMeetings.folder().items[2]);
  })()`);
  assert.equal(await execute("document.querySelectorAll('.document-slide').length"),2);
  assert.equal(await execute("!!document.getElementById('import-powerpoint')"),false);
  await execute("document.querySelectorAll('.document-slide')[1].click()");
  assert.equal(await execute('state.image'),'file:///C:/slide-two.png');
  await execute(`(async()=>{
    const canvas=document.createElement('canvas');canvas.width=160;canvas.height=90;
    const ctx=canvas.getContext('2d');ctx.fillStyle='orange';ctx.fillRect(0,0,160,90);
    const stream=canvas.captureStream(15),recorder=new MediaRecorder(stream,{mimeType:'video/webm'}),chunks=[];
    recorder.ondataavailable=e=>{if(e.data.size)chunks.push(e.data);};
    const recorded=new Promise(resolve=>recorder.onstop=resolve);recorder.start();
    let frame=0;const timer=setInterval(()=>{ctx.fillStyle='rgb('+((frame++*20)%255)+',110,20)';ctx.fillRect(0,0,160,90);stream.getVideoTracks()[0].requestFrame();},40);
    await new Promise(resolve=>setTimeout(resolve,1500));recorder.stop();await recorded;clearInterval(timer);stream.getTracks().forEach(t=>t.stop());
    await ProMaxFeatures.addVideos([new File(chunks,'meeting-test.webm',{type:'video/webm'})]);
    const asset=ProMaxFeatures.getVideos()[0];ProMaxMeetings.add({type:'video',assetId:asset.id,title:asset.name});
    await ProMaxMeetings.open(ProMaxMeetings.folder().items[3]);
  })()`);
  assert.equal(await execute("document.querySelectorAll('.meeting-video-preview').length"),1);
  assert.equal(await execute("document.querySelectorAll('.youtube-library').length"),0);
  assert.equal(await execute('state.image'),'file:///C:/slide-two.png','Video selection preserves the live slide');
  await execute("[...document.querySelectorAll('#feature-view button')].find(b=>b.textContent==='Show on presentation').click()");
  await new Promise(resolve=>setTimeout(resolve,150));
  assert.equal(await execute('state.video?.title'),'meeting-test.webm',await execute('JSON.stringify({toast:document.getElementById("toast").textContent,videos:[...document.querySelectorAll("video")].map(v=>({src:v.src,ready:v.readyState,error:v.error?.message})),asset:ProMaxFeatures.getVideos()[0]})'));
  await execute(`(async()=>{
    await ProMaxYouTubeLibrary.ready;const entry={id:'meeting-test-youtube',videoId:'M7lc1UVf-VE',title:'Meeting YouTube',start:0};
    ProMaxYouTubeLibrary.list().push(entry);await storedAsset('put',ProMaxYouTubeLibrary.list(),'youtube-list');
    ProMaxMeetings.add({type:'youtube',assetId:entry.id,title:entry.title});await ProMaxMeetings.open(ProMaxMeetings.folder().items[4]);
  })()`);
  assert.equal(await execute("document.querySelectorAll('.youtube-card').length"),1);
  assert.equal(await execute("document.querySelectorAll('.asset-row').length"),0);
  assert.equal(await execute("!!document.getElementById('youtube-link')"),false);
  assert.equal(await execute('state.video.title'),'meeting-test.webm','YouTube selection preserves live video');
  assert.equal(await execute('ProMaxYouTubeLibrary.prepared()'),null,'Selecting YouTube does not prepare or play it');
  await execute("ProMaxMeetings.open(ProMaxMeetings.folder().items[1])");
  const reviewDisplay=screen.getAllDisplays().find(d=>d.id!==screen.getPrimaryDisplay().id)||screen.getPrimaryDisplay();
  win.setPosition(reviewDisplay.workArea.x,reviewDisplay.workArea.y);win.showInactive();
  await new Promise(resolve=>setTimeout(resolve,250));
  fs.writeFileSync(path.join(app.getPath('temp'),'promax-meeting-item-workspace.png'),(await win.webContents.capturePage()).toPNG());
  await execute("ProMaxMeetings.remove(4);ProMaxMeetings.remove(3);ProMaxMeetings.remove(2)");
  await execute("ProMaxMeetings.remove(1)");
  assert.equal(await execute(`songs.some(s=>s.id===${JSON.stringify(testSong)})`),true);
  await execute("ProMaxMeetings.create('Another meeting')");
  assert.equal(await execute("document.querySelectorAll('.meeting-item').length"),0);
  assert.equal(await execute("meetingFolders[0].items.length"),1);
  await execute("document.getElementById('quick-text').value='Welcome to the meeting';document.getElementById('quick-text').dispatchEvent(new Event('input'));document.getElementById('quick-add-meeting').click()");
  assert.equal(await execute("ProMaxMeetings.folder().items[0].type"),'text');
  await execute("ProMaxMeetings.open(ProMaxMeetings.folder().items[0]);document.querySelector('.prepared-slide').click()");
  assert.equal(await execute("state.text"),'Welcome to the meeting');
  assert.equal(await execute("JSON.parse(localStorage.getItem('promax-library')).settings.quickText"),'Welcome to the meeting');
  await execute("ProMaxMeetings.select(meetingFolders[0].id)");
  await execute("ProMaxMeetings.select(null)");
  assert.equal(await execute("document.getElementById('meeting-folder-browser').hidden || document.getElementById('song-library-area').hidden"),false);
  await execute("ProMaxMeetings.select(meetingFolders[0].id)");
  assert.equal(await execute("document.querySelector('.meeting-item.active .meeting-item-open span').textContent"),'Matteus 16:26-27');
  win.setSize(900,950);await new Promise(resolve=>setTimeout(resolve,100));
  assert.equal(await execute("document.documentElement.scrollWidth<=window.innerWidth"),true,'Narrow layout must not overflow');
  win.setSize(1440,1000);
  const display=screen.getAllDisplays().find(d=>d.id!==screen.getPrimaryDisplay().id)||screen.getPrimaryDisplay();
  win.setPosition(display.workArea.x,display.workArea.y);
  win.showInactive();await new Promise(resolve=>setTimeout(resolve,250));
  const image=await win.webContents.capturePage();
  fs.writeFileSync(path.join(app.getPath('temp'),'promax-meeting-layout.png'),image.toPNG());
  fs.writeFileSync(path.join(app.getPath('temp'),'promax-meetings-result.txt'),'PASSED: meeting creation, song and Bible additions, ordering, prepared slides, autosave, restart persistence, removal preserves library, folder isolation.');
  app.exit(0);
}).catch(error=>{fs.writeFileSync(path.join(app.getPath('temp'),'promax-meetings-result.txt'),error.stack);app.exit(1);});
